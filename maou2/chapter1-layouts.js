// A row in a plan paints an inclusive rectangle. Rectangles are the walls,
// landings and floor of a particular built place. Order matters at junctions.
function authoredFloor(width,height,ground,plan) {
  const rows=Array.from({length:height},()=>Array(width).fill(ground));
  for(const line of plan.trim().split(/\n+/)){
    const [tile,...coords]=line.trim().split(/\s+/);
    const [x0,y0,x1,y1]=coords.map(Number);
    if(!(0<=x0&&x0<=x1&&x1<width&&0<=y0&&y0<=y1&&y1<height))throw Error("Invalid chapter one floor: "+line);
    for(let y=y0;y<=y1;y++)for(let x=x0;x<=x1;x++)rows[y][x]=tile;
  }
  return rows.map(row=>row.join(""));
}
function chapterFloor(title,theme,width,height,ground,start,plan,props,lamps,front=[],safe=false) {
  const places=entries=>entries.map(([col,row,kind,look])=>({col,row,kind,look,chapterProp:true}));
  return {title,theme,chapter:1,skin:theme==="road"?"road":"castle",safe,start,scroll:true,
    grid:authoredFloor(width,height,ground,plan),
    backdrop:{props:places(props),front:places(front),lamps}};
}
