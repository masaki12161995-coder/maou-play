// 「話し手：台詞」を1行ずつ。同じ人が続けて話すときは、同じ窓の中で送っていく
async function talk(text) {
  let cur = null, pages = [], narr = false;
  const flush = async () => { if (pages.length) await UI.say(cur, pages, { narr }); pages = []; };
  for (const raw of text.split("\n")) {
    const l = raw.trim(); if (!l) continue;
    let nm, body, n = false;
    if (l[0] === "〔") { nm = ""; body = l.slice(1, -1); n = true; }
    else { const i = l.indexOf("："); nm = l.slice(0, i); body = l.slice(i + 1); nm = NAME[nm] || nm; }
    if (nm !== cur || n !== narr) { await flush(); cur = nm; narr = n; }
    pages.push(body);
  }
  await flush();
}
