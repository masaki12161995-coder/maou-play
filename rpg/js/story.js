// 1回目は吹き出しを全部、2回目からは最後の1つだけ
const STAGE_KEY = v => v === 0 ? "0a" : v === 0.5 ? "0b" : String(v);
// 町ごとの切りかわり（物語担当の「仕組み担当への連絡」のとおり）。ハルネと大橋は、橋がつながった夜明けから段階2
// 森の婆の庵は、序章が段階0、第1章からが段階1、第2章の葬列の後から段階2
const PLACE_STAGE = { zahara: g => "3a", harune: g => (g.flags.s < 28 ? 1 : 2), hermit: g => ((g.flags.s || 0) < 14 ? "0" : (g.flags.s || 0) < 47 ? "1" : "2") };
// as：台詞を言う人を差しかえる（ガルムが旅に出た後は、甥のコガルムが同じ台詞を言う）
async function townTalk(place, who, n, as) {
  const key = STAGE_KEY((PLACE_STAGE[place] || root.townStage)(G())), pick = k => ((TOWNTALK[place] || {})[k] || []).filter(b => b.who === who || b.who.split("（")[0] === who);
  let list = pick(key); if (!list.length && /b$/.test(key)) list = pick(key.replace(/b$/, "a")); // 「3-b」は差しかえる人だけ。ほかの人は「3-a」のまま
  const blk = list[n || 0] || list[0];
  if (!blk) return false;
  const f = F(); f.tk = f.tk || {}; const id = `${place}:${key}:${who}:${n || 0}`;
  let lines = f.tk[id] ? [blk.lines[blk.lines.length - 1]] : blk.lines;
  if (as) lines = lines.map(l => l.startsWith(who + "：") ? as + l.slice(who.length) : l);
  await talk(lines.join("\n"));
  f.tk[id] = 1;
  return key;
}
