function pair(id, a, b, title, after, site, setup, exchange, ways, limits = {}) {
  const members = [a,b];
  const lines = [narrated(setup), ...exchange.map((line,index) => [members[index % 2],line])];
  const choices = ways.map(([label,replyA,replyB],index) => ({ key:`way-${index+1}`, label, reply:[[a,replyA],[b,replyB]] }));
  return { id, members, title, after, site, post:after === 'POST', ...limits, scenes:[{site,lines,choices}] };
}

