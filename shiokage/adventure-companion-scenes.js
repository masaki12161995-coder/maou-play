const hero = 84;
const narrated = line => [0, line];

function individual(id, title, after, town, site, opening, question, a, b, bad) {
  const choices = [a,b].map(([label,reply,detail],index) => ({ key:`way-${index+1}`, label, detail, reply:[[id,reply]] }));
  if(bad) {
    const [label, reply, detail, reason] = bad;
    choices.push({ key:'leave', label, detail, departure:reason, reply:[[id,reply]] });
  }
  return {
    title, after, site:town, members:[id], post:after === 'POST',
    scenes:[
      { site:town, lines:[narrated(opening[0]),[id,opening[1]]] },
      { site, lines:[narrated(question[0]),[hero,question[1]]], choices },
      { site, lines:[narrated('帰り支度を始める。')],
        followup:{'way-1':[[id,a[3]]],'way-2':[[id,b[3]]]} }
    ]
  };
}

