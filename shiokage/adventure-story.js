export const adventureChapterCode = chapter => `C${String(chapter).padStart(2,'0')}`;

export function newAdventure() {
  return {chapter:1, flags:{START:true}, cleared:{}, choices:{}, personal:{}, pairs:{}, seen:{}, gear:{}, nextGear:1, ending:null};
}

export function normalizeAdventure(raw) {
  if (!raw || typeof raw !== 'object') return null;
  const state = newAdventure();
  for (const field of ['flags','cleared','choices','personal','pairs','seen','gear']) {
    if (raw[field] && typeof raw[field] === 'object' && !Array.isArray(raw[field])) state[field] = raw[field];
  }
  state.flags.START = true;
  state.nextGear=Math.max(1,Math.floor(Number(raw.nextGear)||1));
  state.chapter = 1;
  while (state.chapter < 12 && state.flags[adventureChapterCode(state.chapter)]) state.chapter++;
  if (state.flags.C12 && ['E1','E2','E3'].includes(raw.ending)) {
    state.ending = raw.ending;
    state.flags.POST = true;
  }
  return state;
}

export function availableAdventureEndings(adventure, members, lost) {
  const {flags} = adventure;
  const endings = [{id:'E1',label:'小さな竜を海へ放す',note:'竜は自由になる。沿岸の火は消え、人は高い道へ移る。'}];
  if (flags.G01 && flags.G02 && !flags.W03 && !flags.W05) {
    for (const [id,name] of [[33,'クオ'],[48,'リュネ']]) {
      if (members.includes(id) && !lost[id]) endings.push({id:'E2',volunteer:id,label:name+'に託す',note:name+'は竜と沖に残り、旅の隊列から永久に外れる。'});
    }
  }
  if (flags.W05) endings.push({id:'E3',label:'鎖で港だけを守らせる',note:'自分の港に火が戻る。他の岸には黒い波が来る。'});
  return endings;
}

