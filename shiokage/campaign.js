export function addCampaign(recruits, dangers) {
  extendWorld();
  for (let i=0;i<regions.length;i++) {
    const town=townMap(i,regions[i],recruits);
    maps[town.id]=town;
  }
  for (const c of Object.values(chapters)) {
    story.push({title:c.title,hint:c.hint});
  }
  story.splice(3,1);
  story.push({title:'受け取った声',hint:'鐘が止まった場所で、返事を届ける相手を選ぶ。'});
  story.push({title:'潮の返事を追う',hint:'終渡しの町に残った札を読み、まだ届いていない返事を迎えに行く。'});
  Object.assign(maps,dangers);
  for(const q of errands) {
    const town=maps[q.town], site=maps[q.site];
    town.objects.push({id:q.town+'-errand',kind:'errand',label:q.label,...tilePoint(townLayouts[q.town]?.services.errand??[523,685])});
    const trace=site.objects.find(o=>o.kind==='sign')??site.objects.find(o=>o.kind==='chest');
    if(q.town==='port') {
      site.objects.push({id:q.site+'-errand',kind:'errandTrace',errand:q.town,label:q.trace,x:425,y:407});
    } else if(trace) {
      trace.errand=q.town;
    }
  }
  const {postCard,postExits}=townLayouts.lastwharf;
  maps.lastwharf.objects.push({id:'post-card',kind:'post',...tilePoint(postCard),label:'返事のない木札'});
  maps.lastwharf.exits.push(
    {id:'below',kind:'cave',...tilePoint(postExits[0]),label:'潮床の外法',post:true,returnSpawn:{x:534,y:435,face:0}},
    {id:'afterbell',kind:'cave',...tilePoint(postExits[1]),label:'弔いの外縁',post:true}
  );
  for(const map of Object.values(maps)){
    for(const exit of map.exits??[]) {
      if(exit.spawn||!maps[exit.id]) continue;
      const into=maps[exit.id], back=into.exits?.find(d=>d.id===map.id);
      exit.spawn=back&&map.kind==='cave'?(back.returnSpawn??{x:back.x+6,y:back.y+42,face:0}):{...into.entry};
    }
  }
}
