export function townReaction(id,state,mapId) {
  const chapter=townStages[mapId];
  if(!chapter||state.lost?.[id]) return undefined;
  if(state.ending){
    const outcome=outcomeVoices[mapId]?.[state.ending]?.[id];
    if(outcome) return outcome;
  }
  const voyage=voyageVoices[mapId]?.[id];
  if(voyage&&state.voyages?.[voyage[0]]?.step>=8){
    const [,line,choice,alternate]=voyage;
    return choice&&state.voyages[voyage[0]].choices?.report===choice?alternate:line;
  }
  if(mapId==='ember'&&id===123&&state.chapter>7){
    const route=state.flags?.['route-7'];
    if(route==='tell') return '告げ札の前で知ってる顔が足を止める。わしは聞かれたことだけ話す。誰を家に入れるかは、その人が選ぶこった。';
    if(route==='hide') return '表に出す写しは焼けた。町で知らない人の前まで出たら、わしは口で話す。';
  }
  if(mapId==='threshold'&&id===98&&state.chapter>8){
    if(state.flags?.['route-8']==='cut') return 'あの便だけ紙では返せない。足で戻ってきた人から、声を受け取る場所に変えた。';
    if(state.flags?.['route-8']==='keep') return '結んだ返事は預かってる。受け取る人が来たら、急かさず自分で糸をほどいてもらう。';
  }
  if(state.flags?.['aftermath-'+chapter]||state.chapter>chapter)
    return localVoices[mapId]?.[id];
  return undefined;
}

