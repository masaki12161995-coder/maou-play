export const traveling = (id,state) => state.party?.includes(id) && !state.lost?.[id];

export function chapterScene(chapter,part,state) {
  const chapterData=chapters[chapter];
  if(!chapterData) return [];
  const lines=[...chapterData[part]];
  if(chapter===8&&part==='before'){
    if(traveling(35,state)) lines.push(
      [35,'うん。父上と見送ったのは十年前。潮下は名前を返せと言った。私は代わりに、あなたが生きて歩いた日を返してくれ、と頼んだ。'],
      [84,'だからあの朝、帰ったと呼んだのか。……今度は僕の名を、僕より先に渡した？'],
      [35,'向こうにも返事を待つ人がいた。隠せばまた十年待たせる。名板は渡したけれど、あなたの話す番までは渡していない。']
    );
    else lines.push(
      [0,'封の筆跡は、港の朝番が使うものだった。「十年前、あなたを見送った。潮下から生きた日を返してもらい、今度はあなたの名を先に預けた。話す番は、あなたに残したかった」'],
      [84,'小さいころの記憶と、ここまで一緒に歩いた日の記憶は、どっちも僕の中にある。両方を持って会いに行く。']
    );
  }
  if(part==='after'){
    const route=chapterRouteNotes[chapter]?.[state.flags?.['route-'+chapter]];
    if(route) lines.push([0,route]);
    const witness=companionWitnesses[chapter];
    if(witness&&traveling(witness[0],state)) lines.push(witness);
  }
  return lines;
}

