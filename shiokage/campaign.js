export function captureEnding(state) {
  const flags=state.flags??{};
  return {
    ena:flags.enaAnswer??'',
    enaPresent:!!traveling(35,state),
    lostEna:!!state.lost?.[35],
    conduct:state.ethic??0,
    allies:state.members?.length??1,
    routes:Object.fromEntries(Object.keys(chapters).map(n=>[n,flags['route-'+n]??'proof'])),
    returns:errands.filter(q=>state.clues?.['errand-'+q.town]==='returned').length
  };
}

