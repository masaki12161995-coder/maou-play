const HERO = 84;
const note = text => [0, text];
const hero = text => [HERO, text];
const pages = (speaker, lines) => lines.map(line => typeof line === 'string' ? [speaker, line] : line);

export const companionJourneys = Object.create(null);
export const relationshipJourneys = [];

function decision(speaker, key, [label, detail, reply, aftermath]) {
  return {
    choice: {key, label, detail, reply: pages(speaker, reply)},
    aftermath: pages(speaker, aftermath)
  };
}

function account(id, chapter, site, title, place, opening, observation, options, closing) {
  const alternatives = options.map((option, index) => decision(id, String(index + 1), option));
  companionJourneys[id] = {
    title, chapter,
    scenes: [
      {lines:pages(id, opening)},
      {site, place, lines:pages(id, observation), choices:alternatives.map(option => option.choice)},
      {site, place, lines:[], followup:Object.fromEntries(alternatives.map(({choice, aftermath}) => [choice.key, aftermath]))},
      {lines:pages(id, closing)}
    ]
  };
}

