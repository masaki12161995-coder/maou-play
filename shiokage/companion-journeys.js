function dispute(a, b, chapter, title, argument, proof, first, second) {
  const exchange = lines => lines.map((line, index) => typeof line === 'string' ? [index % 2 ? b : a, line] : line);
  const choices = [first, second].map(([label, detail, lines, resolution], index) => ({
    key:String(index + 1), label, detail, reply:exchange(lines), resolution:exchange(resolution)
  }));
  relationshipJourneys.push({
    id:a+'-'+b, members:[a,b], title, chapter,
    scenes:[
      {lines:exchange(argument)},
      {lines:exchange(proof), choices:choices.map(({resolution, ...choice}) => choice)},
      {lines:[], followup:Object.fromEntries(choices.map(choice => [choice.key, choice.resolution]))}
    ]
  });
}

