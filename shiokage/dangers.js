function trail(id, label, x, y) {
  return { id, label, x, y, kind: 'town' };
}

function sign(id, label, x, y, text) {
  return { id, label, x, y, kind: 'sign', text };
}

function camp(id, label, x, y, text) {
  return { ...sign(id, label, x, y, text), inn: true };
}

function chest(id, label, x, y, loot) {
  return { id, label, x, y, kind: 'chest', loot };
}

function seal(id, label, x, y, monster, chapter, text, loot = {}) {
  return { id: `${id}-seal`, label, x, y, kind: 'boss', boss: [monster], chapter, text, loot, postgame: chapter === undefined };
}

