const H = 84;
const page = (speaker, text) => [speaker, text];
const narrate = (...lines) => lines.map(text => page(0, text));
const hear = (label, detail, reply, config={}) => ({key:'listen',label,detail,reply:narrate(...reply),...config});
const fight = (label, detail, enemies, reply, config={}) =>
  ({key:'fight',label,detail,battle:{enemies},reply:narrate(...reply),...config});
const step = (key, label, lines, choices, hint) =>
  ({key,label,lines:lines.map(line=>Array.isArray(line)?line:page(0,line)),choices,hint:hint??label});

export const voyages = {};

function voyage(id, setup, stages) {
  const {home,entry,gate,returnAt,...data}=setup;
  voyages[id]={
    id,...data,home,
    entry:{map:home,x:entry[0],y:entry[1]},
    gate,returnAt,stages
  };
}

