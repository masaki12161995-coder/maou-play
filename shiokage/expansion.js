export function installExpansion(maps, monsterDefs) {
  Object.assign(monsterDefs,expansionMonsters);
  for(const arc of Object.values(voyages)) {
    const outerId='voyage-'+arc.id+'-shore';
    const innerId='voyage-'+arc.id+'-deep';
    if(maps[outerId]) continue;
    const home=maps[arc.home];
    const access={voyage:arc.id,chapter:arc.chapter,post:arc.post};
    const [outer,inner]=arc.layouts.map(key=>layouts[key]);
    const outerTop=[outer.top[0],outer.top[1]+(arc.layouts[0]==='fork'?110:70)];
    home.objects.push(stageObject(arc,arc.stages[0],[arc.entry.x,arc.entry.y]));
    home.objects.push(stageObject(arc,arc.stages.at(-1),arc.returnAt));
    home.exits.push(waypoint(outerId,arc.sites[0],arc.gate,mark(outer.entry),{...access,minStep:1}));
    const homeArrival=mark([arc.entry.x,arc.entry.y+36],2);
    const seed=arithmeticSeed(arc.id);
    for(const [n,preset,place] of [[0,outer,outerId],[1,inner,innerId]]) {
      const [width,height]=preset.size;
      const exits=n===0
        ? [waypoint(arc.home,home.name,preset.bottom,homeArrival),waypoint(innerId,arc.sites[1],preset.top,mark(inner.entry),{...access,minStep:4})]
        : [waypoint(outerId,arc.sites[0],preset.bottom,mark(outerTop,0)),
          waypoint(arc.home,'町へ戻る抜け道',[preset.top[0],preset.top[1]+33],homeArrival,{...access,minStep:7})];
      const start=1+n*3;
      const objects=arc.stages.slice(start,start+3).map((stage,ix)=>stageObject(arc,stage,preset.rooms[ix]));
      maps[place]={
        id:place,name:arc.sites[n],kind:'cave',tier:arc.tier,palette:arc.palette[n],
        width,height,seed:seed+n*43,entry:mark(preset.entry),caveWidth:preset.width,pathWidth:42,
        scatter:100,paths:[preset.main,...preset.forks],lakes:preset.lakes,bridges:preset.bridges,
        ground:preset.ground,props:preset.props,people:[],exits,objects,encounters:[]
      };
    }
  }
}

function arithmeticSeed(id) {
  let seed=181;
  for(const char of id) seed=(seed*31+char.charCodeAt(0))%811111;
  return seed;
}

