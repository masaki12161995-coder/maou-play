function pair(a,b,chapter,title,exchange,left,right) {
  const option=([label,answerA,answerB],ix)=>({
    key:ix===0?'first':'second',label,
    detail:ix===0?'先に二人の話を聞く':'別のやり方を二人に提案する',
    reply:[page(a,answerA),page(b,answerB)]
  });
  campPairs.push({
    id:'pair-'+a+'-'+b,members:[a,b],chapter,title,
    lines:exchange.map((text,ix)=>page(ix%2===0?a:b,text)),
    choices:[option(left,0),option(right,1)]
  });
}

