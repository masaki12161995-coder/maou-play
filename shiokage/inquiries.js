export function installInquiries(maps){
  for(const entry of Object.values(inquiries)){
    for(const [index,record] of entry.evidence.entries()){
      const map=maps[record.map],anchor=map.objects.find(point=>point.id===record.anchor);
      const id='inquiry-'+entry.id+'-'+index;
      record.hint=map.name+'　'+record.place;
      if(map.objects.some(point=>point.id===id)) continue;
      map.objects.push({id,kind:'inquiry',inquiry:entry.id,index,label:record.label,x:anchor.x+record.dx,y:anchor.y+record.dy});
    }
  }
}
