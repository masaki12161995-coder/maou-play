const style = (shape,palette,mirrored=false) => ({shape,palette,mirrored});
const point = ([x,y],face=3) => ({x,y,face});
const marker = (arc,stage,position) => ({...point(position),id:'journey-'+arc.id+'-'+stage.key,
  kind:'voyage',arc:arc.id,step:stage.key,label:stage.label});
const gate = (id,label,position,spawn,rule={}) => ({...point(position),id,label,kind:'cave',spawn,...rule});

function plan({shape,palette,mirrored}) {
  const {entry,out,end,main,nooks,links=[],lakes,ground=[],props}=footprints[shape];
  const turn = ([x,y]) => [mirrored?940-x:x,y];
  const turnRect = ([x,y,...rest]) => [...turn([x,y]),...rest];
  const turnProp = ([kind,x,y,...rest]) => [kind,...turn([x,y]),...rest];
  return {palette,entry:turn(entry),out:turn(out),end:turn([end[0],end[1]+56]),paths:[main,...nooks,...links].map(line=>line.map(turn)),
    rooms:nooks.map(line=>turn(line.at(-1))),lakes:lakes.map(turnRect),ground:ground.map(turnProp),props:props.map(turnProp)};
}

export function installJourneys(maps,monsterDefs) {
  Object.assign(monsterDefs,journeyMonsters);
  for (const arc of Object.values(journeys)) {
    const ids=arc.acts.map((_,index)=>'journey-'+arc.id+'-'+index);
    if(maps[ids[0]]) continue;
    const home=maps[arc.home], plans=arc.styles.map(plan);
    const [openAt,enterAt,reportAt,homeSpawn]=arc.access;
    const access={voyage:arc.id,chapter:arc.chapter,post:arc.post};
    home.objects.push(marker(arc,arc.stages[0],openAt),marker(arc,arc.stages.at(-1),reportAt));
    home.exits.push(gate(ids[0],arc.places[0],enterAt,point(plans[0].entry),{...access,minStep:1}));
    let first=1;
    for(const [index,wing] of arc.acts.entries()) {
      const place=plans[index],next=plans[index+1],previous=plans[index-1];
      const retreat=previous?point([previous.end[0],previous.end[1]+67],0):point(homeSpawn,0);
      const advance=next?point(next.entry):point(homeSpawn,0);
      const exits=[gate(ids[index-1]??arc.home,arc.places[index-1]??home.name,place.out,retreat),
        gate(ids[index+1]??arc.home,arc.places[index+1]??'町へ戻る抜け道',place.end,advance,{...access,minStep:first+wing.length})];
      const seed=Number.parseInt(arc.id.slice(0,2),10)*97+index*43;
      maps[ids[index]]={id:ids[index],name:arc.places[index],kind:'cave',tier:arc.tier,level:arc.level,palette:place.palette,
        width:940,height:920,seed,entry:point(place.entry),caveWidth:86,pathWidth:40,scatter:0,
        paths:place.paths,lakes:place.lakes,ground:place.ground,props:place.props,people:[],exits,
        objects:wing.map((stage,slot)=>marker(arc,stage,place.rooms[slot])),encounters:[]};
      first+=wing.length;
    }
  }
}

