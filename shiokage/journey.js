function journey(id,{home,chapter,level,tier,post,requires,title,places,access,styles},acts) {
  const {open,report,wings}=acts;
  open.hint='町の「'+open.label+'」で話を聞く。';
  report.hint='町へ戻り、「'+report.label+'」で結果を伝える。';
  for(const [index,wing] of wings.entries()){
    for(const stage of wing) stage.hint='「'+places[index]+'」で「'+stage.label+'」を調べる。';
  }
  const stages=[open,...wings.flat(),report];
  journeys[id]={id,home,chapter,level,tier,post,requires,title,places,access,styles,acts:wings,stages,
    entry:{map:home,x:access[0][0],y:access[0][1]}};
}

