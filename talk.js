// 条件：'フラグ'・'!フラグ'・'ch3+'・'ch<4' を & でつなぐ
function talkCond(c){
  if(!c) return true;
  return String(c).split('&').every(t=>{ t=t.trim(); let m;
    if((m=t.match(/^ch(\d+)\+$/))) return G.chapter>=+m[1];
    if((m=t.match(/^ch<(\d+)$/))) return G.chapter<+m[1];
    if(t[0]==='!') return !G.flags[t.slice(1)];
    return !!G.flags[t]; });
}
function townPhase(id){
  const c=G.chapter;
  if(c>=5) return 'c';
  if(c<=(TOWN_CH[id]??0) && !(TOWN_DONE[id] && G.flags[TOWN_DONE[id]])) return 'a';
  return 'b';
}
// その町で、いま話せるセリフの一覧（町の言葉 → うわさ → ひとりごと の順）
function townPool(id){
  const T=TOWN_TALK[id]; const ph=townPhase(id); const out=[];
  if(T){ const lines=T[ph]||T.b||T.c||T.a||[]; for(const [w,t,c] of lines) if(talkCond(c)) out.push({who:w,text:t}); }
  const ch=Math.min(G.chapter,7);
  for(const r of (RUMOR[ch]||[])){ const [t,c]=Array.isArray(r)?r:[r]; if(talkCond(c)) out.push({who:null,text:t}); }
  for(const t of (G.chapter>=5?FLAVOR_DARK:FLAVOR)) out.push({who:null,text:t});
  return out;
}
// 名前のないセリフには、町の人らしい呼び名を順に（町の中で重ならないように）
const GENERIC_WHO=['通りがかりの人','買い物帰りの人','見物人','荷運びの男','散歩中の老人','若い職人','子連れの母親','物売り','井戸端の女','見回りの兵士','旅の楽士','水売り','靴みがき','洗濯女','煙突掃除','鳩にえさをやる人'];
function townLine(id, n){
  const pool=townPool(id); if(!pool.length) return null;
  const k=((n.fi||0) + (G.innCount||0)*3) % pool.length;
  const L=pool[k]; const used=new Set(pool.filter(x=>x.who).map(x=>x.who));
  // 名前のないセリフは、一覧の中での順番で呼び名を決める（順番は一人ずつちがうので、名前も重ならない）
  let who=L.who; if(!who){ const free=GENERIC_WHO.filter(w=>!used.has(w)); const firstGen=pool.findIndex(x=>!x.who); who=free[(k-firstGen)%free.length]||'町の人'; }
  return {who, text:L.text};
}
